// Every native command a WebView can reach must be registered, declared to the
// ACL manifest, have generated permissions and be granted by exactly one
// capability. The fixture is the reviewed union; the checks read the real files.
import test from "node:test";
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";

const root = new URL("../src-tauri/", import.meta.url);
const text = (name) => readFile(new URL(name, root), "utf8");
const expected = JSON.parse(await readFile(new URL("fixtures/native-commands.json", import.meta.url), "utf8"));
const union = Object.values(expected).flatMap((capability) => capability.commands).sort();
const sorted = (values) => [...values].sort();

test("registered handler commands are exactly the reviewed union", async () => {
  const source = await text("src/note_host.rs");
  const blocks = [...source.matchAll(/generate_handler!\s*\[([^\]]+)\]/gs)];
  assert.equal(blocks.length, 1, "one Tauri command registration");
  const registered = blocks[0][1].split(",").map((entry) => entry.trim().split("::").at(-1)).filter(Boolean);
  assert.deepEqual(sorted(registered), union);
});

test("the app manifest declares every registered command", async () => {
  const manifest = (await text("build.rs")).match(/AppManifest::new\(\)\.commands\(&\[([^\]]+)\]/s);
  assert.ok(manifest, "app command manifest");
  const declared = [...manifest[1].matchAll(/"([a-z_]+)"/g)].map(([, name]) => name);
  assert.deepEqual(sorted(declared), union);
});

test("each command has its generated allow permission", async () => {
  const dir = new URL("permissions/autogenerated/", root);
  const files = (await readdir(dir)).filter((name) => name.endsWith(".toml"));
  assert.deepEqual(sorted(files.map((name) => name.slice(0, -5))), union);
  for (const command of union) {
    const toml = await readFile(new URL(`${command}.toml`, dir), "utf8");
    const allow = `allow-${command.replaceAll("_", "-")}`;
    assert.match(toml, new RegExp(`identifier = "${allow}"[\\s\\S]*?commands\\.allow = \\["${command}"\\]`));
  }
});

test("native alert notifications have no WebView permission", async () => {
  const manifest = await text("build.rs");
  assert.match(manifest, /\.plugin\("notify", notify\)/);
  const dir = new URL("capabilities/", root);
  for (const file of (await readdir(dir)).filter(name => name.endsWith('.json'))) {
    const config = await readFile(new URL(file, dir), 'utf8');
    assert.doesNotMatch(config, /notify:allow-notify/, `${file} must not let a page post a native notification`);
  }
});

test("capabilities grant each command once, to its reviewed windows only", async () => {
  const dir = new URL("capabilities/", root);
  const granted = new Map();
  for (const name of (await readdir(dir)).filter((file) => file.endsWith(".json"))) {
    const capability = JSON.parse(await readFile(new URL(name, dir), "utf8"));
    const want = expected[capability.identifier];
    assert.ok(want, `unexpected capability ${capability.identifier}`);
    assert.deepEqual(capability.windows, want.windows);
    assert.deepEqual(capability.platforms, want.platforms);
    // Core and scanner plugin grants are only the reviewed narrow capabilities.
    assert.deepEqual(sorted(capability.permissions),
      sorted([...want.commands.map((command) => `allow-${command.replaceAll("_", "-")}`),
        ...(want.core ?? []), ...(want.plugins ?? [])]));
    for (const command of want.commands) {
      assert.ok(!granted.has(command), `${command} granted twice`);
      granted.set(command, capability.identifier);
    }
  }
  assert.deepEqual(sorted(granted.keys()), union);
  const config = JSON.parse(await text("tauri.conf.json"));
  assert.deepEqual(sorted(config.app.security.capabilities), sorted(Object.keys(expected)));
});
