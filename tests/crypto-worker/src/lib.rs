//! Fixed vectors from native bh-crypto/libsodium, no signing key in the Worker.

#[unsafe(no_mangle)]
pub extern "C" fn check_crypto() -> i32 {
    let public = [
        0xea, 0x4a, 0x6c, 0x63, 0xe2, 0x9c, 0x52, 0x0a, 0xbe, 0xf5, 0x50, 0x7b, 0x13, 0x2e, 0xc5,
        0xf9, 0x95, 0x47, 0x76, 0xae, 0xbe, 0xbe, 0x7b, 0x92, 0x42, 0x1e, 0xea, 0x69, 0x14, 0x46,
        0xd2, 0x2c,
    ];
    let signature = [
        0x9e, 0x46, 0xad, 0x09, 0x52, 0x42, 0x48, 0x6a, 0xb6, 0x8b, 0x0b, 0x66, 0x64, 0xad, 0xe0,
        0x90, 0x9c, 0x98, 0xe0, 0x2d, 0xe0, 0x19, 0xd9, 0x88, 0x10, 0xc4, 0x48, 0xd7, 0xe5, 0x8d,
        0x43, 0x19, 0xc8, 0xae, 0x94, 0x1a, 0x47, 0x4f, 0x6e, 0xf6, 0x4e, 0xa9, 0xdd, 0x22, 0x10,
        0x6c, 0x5c, 0x52, 0x19, 0x6e, 0x47, 0x28, 0xf9, 0xa3, 0x46, 0x47, 0x37, 0xbb, 0xac, 0x84,
        0xdf, 0x2f, 0xab, 0x0a,
    ];
    if bh_crypto::hash(b"")
        != [
            0x0e, 0x57, 0x51, 0xc0, 0x26, 0xe5, 0x43, 0xb2, 0xe8, 0xab, 0x2e, 0xb0, 0x60, 0x99,
            0xda, 0xa1, 0xd1, 0xe5, 0xdf, 0x47, 0x77, 0x8f, 0x77, 0x87, 0xfa, 0xab, 0x45, 0xcd,
            0xf1, 0x2f, 0xe3, 0xa8,
        ]
    {
        return 1;
    }
    // Independent Python hashlib.blake2b(b"abc", digest_size=32) vector.
    const ABC: [u8; 32] = [
        0xbd, 0xdd, 0x81, 0x3c, 0x63, 0x42, 0x39, 0x72, 0x31, 0x71, 0xef, 0x3f, 0xee, 0x98, 0x57,
        0x9b, 0x94, 0x96, 0x4e, 0x3b, 0xb1, 0xcb, 0x3e, 0x42, 0x72, 0x62, 0xc8, 0xc0, 0x68, 0xd5,
        0x23, 0x19,
    ];
    if bh_crypto::hash(b"abc") != ABC {
        return 5;
    }
    if bh_crypto::hash(b"abd") == ABC {
        return 6;
    }
    if bh_crypto::verify(&public, b"message", &signature).is_err() {
        return 2;
    }
    if bh_crypto::verify(&public, b"other", &signature).is_ok() {
        return 3;
    }
    let mut forged = signature;
    forged[0] ^= 1;
    if bh_crypto::verify(&public, b"message", &forged).is_ok() {
        return 4;
    }
    0
}
