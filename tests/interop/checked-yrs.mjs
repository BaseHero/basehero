// Native Note interop controls from pinned Yjs; --write refreshes committed v1 bytes.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import * as Y from 'yjs';

const doc = id => { const d = new Y.Doc(); d.clientID = id; return d; };
const a = doc(2 ** 53 - 1);
const b = doc(7);
a.transact(() => {
  const t = a.getText('t');
  t.insert(0, 'hello 😀 world');
  t.format(0, 5, { bold: true, color: '#f00' });
  t.insertEmbed(3, { image: 'x', w: 3 });
  const m = a.getMap('m');
  for (const n of [0, -1, -300, 1, 2 ** 31 - 1, -(2 ** 31), 2 ** 31,
    2 ** 53 - 1, -(2 ** 53 - 1), 1.5, 123456789012n]) m.set(String(n), n);
  m.set('nested', { a: [1, [2, { b: null, c: true }]] });
  m.set('bin', new Uint8Array([1, 2, 3]));
  const arr = a.getArray('arr');
  arr.insert(0, [1, 'two', { three: 3 }, [4]]);
  arr.insert(0, [new Y.Map()]);
  const x = a.getXmlFragment('x');
  const el = new Y.XmlElement('p');
  el.setAttribute('k', 'v');
  el.insert(0, [new Y.XmlText('xt')]);
  x.insert(0, [el]);
  m.set('sub', new Y.Doc({ guid: 'sub-guid', meta: { k: 1 } }));
});
Y.applyUpdate(b, Y.encodeStateAsUpdate(a));
b.getText('t').delete(2, 4);
b.getMap('m').delete('1');
a.getText('t').insert(1, 'Z');
Y.applyUpdate(a, Y.encodeStateAsUpdate(b));
const rich = Y.encodeStateAsUpdate(a);
const check = doc(9);
Y.applyUpdate(check, rich);
assert.equal(check.getText('t').toString(), a.getText('t').toString());
assert.equal(check.getMap('m').get('123456789012'), 123456789012n);
assert.equal(check.getXmlFragment('x').toString(), a.getXmlFragment('x').toString());

const w = doc(42);
const updates = [];
w.on('update', u => updates.push(u));
for (const k of 'abcdef') w.getMap('m').set(k, k);
const gap = Y.mergeUpdates([updates[4], updates[1], updates[0], updates[5]]);
assert(Y.decodeUpdate(gap).structs.some(s => s.constructor.name === 'Skip'));

// Values generated by Yjs alongside the wire fixtures, not decoded by yrs.
const vector = bytes => [...Y.decodeStateVector(bytes)].map(([id, clock]) => [String(id), clock])
  .sort(([a], [b]) => a.localeCompare(b));
const expected = {
  rich: {
    text: a.getText('t').toString(),
    vector: vector(Y.encodeStateVector(a)),
    integers: Object.fromEntries(['-1', '-300', '2147483647']
      .map(key => [key, String(a.getMap('m').get(key))])),
  },
  gap: { vector: vector(Y.encodeStateVectorFromUpdate(gap)) },
};
const expectedUrl = new URL('checked-yrs-expected.json', import.meta.url);
const expectedBytes = `${JSON.stringify(expected, null, 2)}\n`;
if (process.argv.includes('--write')) writeFileSync(expectedUrl, expectedBytes);
else assert.equal(readFileSync(expectedUrl, 'utf8'), expectedBytes, 'expected values differ from Yjs');

for (const [name, bytes] of [['rich', rich], ['gap', gap]]) {
  const url = new URL(`checked-yrs-${name}.bin`, import.meta.url);
  if (process.argv.includes('--write')) writeFileSync(url, bytes);
  else assert.deepEqual(Buffer.from(bytes), readFileSync(url), `${name} fixture differs from Yjs`);
}
console.log(`Yjs 13.6.33 checked yrs fixtures: rich ${rich.length} bytes, merged Skip/gap ${gap.length} bytes`);
